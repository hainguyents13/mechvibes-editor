export type LayoutName = keyof typeof keyboardLayouts;

export type KeyboardSize = Exclude<LayoutName, 'mouse'>;

export type LayoutKey = {
  label: string;
  /** KeyboardEvent.code (or Mouse… code) the key plays under. */
  code: string;
  x: number;
  y: number;
  width: number;
  height: number;
  align: number;
};

// Function to parse keyboard layout and render keys
export function parseKeyboardLayout(
  layout: any[],
  _unitSize: number = 54,
): LayoutKey[] {
  const keys: LayoutKey[] = [];
  let currentY = 0;

  layout.forEach((row) => {
    let currentX = 0;
    let currentProps: {
      w: number;
      h: number;
      x: number;
      y: number;
      a: number;
      code?: string;
    } = { w: 1, h: 1, x: 0, y: 0, a: 4 };

    row.forEach((item: any) => {
      if (typeof item === 'object' && !Array.isArray(item)) {
        // Update current properties
        currentProps = { ...currentProps, ...item };
        if (item.x !== undefined) currentX += item.x;
        if (item.y !== undefined) currentY += item.y;
      } else if (typeof item === 'string') {
        // Create key with current properties
        keys.push({
          label: item,
          code: currentProps.code ?? codeForLabel(item),
          x: currentX,
          y: currentY,
          width: currentProps.w || 1,
          height: currentProps.h || 1,
          align: currentProps.a || 4,
        });
        currentX += currentProps.w || 1;
        // Width, height and code apply to one key only
        currentProps.w = 1;
        currentProps.h = 1;
        currentProps.code = undefined;
      }
    });
    currentY += 1;
  });

  return keys;
}

